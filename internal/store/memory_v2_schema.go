package store

import "strings"

// MemoryV2DDL is additive only. Ordinary opens stop at the compatibility schema
// (15); UpgradeMemoryV2 is the explicit operator/test activation boundary.
const MemoryV2DDL = `
CREATE TABLE memory_session_bindings (
 handle TEXT PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 session_id BIGINT NOT NULL REFERENCES sessions(id),
 assistant TEXT NOT NULL,
 native_id TEXT NOT NULL,
 checkout TEXT NOT NULL,
 parent_handle TEXT REFERENCES memory_session_bindings(handle),
 seen_revisions TEXT NOT NULL DEFAULT '{}',
 provenance TEXT NOT NULL,
 created_at TEXT NOT NULL,
 UNIQUE(project_id, assistant, native_id, checkout)
);
CREATE INDEX idx_v2_binding_session ON memory_session_bindings(project_id, session_id);
CREATE TABLE memory_capture_batches (
 id TEXT PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 source_handle TEXT NOT NULL REFERENCES memory_session_bindings(handle),
 executor_handle TEXT REFERENCES memory_session_bindings(handle),
 trigger TEXT NOT NULL,
 watermark BIGINT NOT NULL,
 state TEXT NOT NULL CHECK(state IN ('pending','in_progress','persisted','no_durable_changes','retry_wait','needs_context')),
 generation BIGINT NOT NULL DEFAULT 0,
 lease_until TEXT NOT NULL DEFAULT '',
 retries BIGINT NOT NULL DEFAULT 0,
 next_retry TEXT NOT NULL DEFAULT '',
 manifest_ready BIGINT NOT NULL DEFAULT 0,
 created_at TEXT NOT NULL,
 updated_at TEXT NOT NULL,
 UNIQUE(source_handle, trigger, watermark)
);
CREATE INDEX idx_v2_capture_pending ON memory_capture_batches(project_id,state,next_retry);
CREATE TABLE memory_write_receipts (
 project_id BIGINT NOT NULL REFERENCES projects(id),
 operation_id TEXT NOT NULL,
 batch_id TEXT REFERENCES memory_capture_batches(id),
 item_key TEXT,
 payload_digest TEXT NOT NULL DEFAULT '',
 state TEXT NOT NULL CHECK(state IN ('pending','persisted')),
 memory_id BIGINT REFERENCES memories(id),
 result_json TEXT NOT NULL DEFAULT '',
 created_at TEXT NOT NULL,
 PRIMARY KEY(project_id,operation_id),
 UNIQUE(batch_id,item_key)
);
CREATE INDEX idx_v2_receipt_digest ON memory_write_receipts(project_id,payload_digest);
CREATE TABLE memory_details (
 memory_id BIGINT PRIMARY KEY REFERENCES memories(id),
 project_id BIGINT NOT NULL REFERENCES projects(id),
 format_version BIGINT NOT NULL,
 rationale TEXT NOT NULL,
 subject_key TEXT NOT NULL,
 scope TEXT NOT NULL,
 source_handle TEXT REFERENCES memory_session_bindings(handle),
 content_digest TEXT NOT NULL,
 completeness TEXT NOT NULL
);
CREATE INDEX idx_v2_subject ON memory_details(project_id,subject_key,scope);
CREATE TABLE memory_evidence (
 id TEXT PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 memory_id BIGINT NOT NULL REFERENCES memories(id),
 source_type TEXT NOT NULL,
 locator TEXT NOT NULL,
 digest TEXT NOT NULL,
 excerpt TEXT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('unverified','source_checked','verified_for_scope','verification_failed')),
 observed_at TEXT NOT NULL,
 verified_at TEXT NOT NULL DEFAULT ''
);
CREATE TABLE memory_relations (
 id TEXT PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 source_id BIGINT NOT NULL REFERENCES memories(id),
 target_id BIGINT NOT NULL REFERENCES memories(id),
 relation_type TEXT NOT NULL CHECK(relation_type IN ('supersedes','contradicts','supports','derived_from')),
 scope TEXT NOT NULL,
 rationale TEXT NOT NULL,
 evidence_id TEXT REFERENCES memory_evidence(id),
 proposer TEXT NOT NULL,
 created_at TEXT NOT NULL,
 CHECK(source_id <> target_id)
);
CREATE INDEX idx_v2_rel_target ON memory_relations(project_id,target_id);
CREATE INDEX idx_v2_rel_source ON memory_relations(project_id,source_id);
CREATE TABLE memory_state_events (
 id INTEGER PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id),
 memory_id BIGINT REFERENCES memories(id),
 relation_id TEXT REFERENCES memory_relations(id),
 event_kind TEXT NOT NULL CHECK(event_kind IN ('proposed','accepted','rejected','retracted','completed','reopened','verified','verification_failed','edited')),
 evidence_id TEXT REFERENCES memory_evidence(id),
 expected_revision BIGINT NOT NULL,
 actor TEXT NOT NULL,
 occurred_at TEXT NOT NULL,
 operation_id TEXT NOT NULL UNIQUE
);
CREATE INDEX idx_v2_state_memory ON memory_state_events(project_id,memory_id,id);
CREATE INDEX idx_v2_state_relation ON memory_state_events(project_id,relation_id,id);
`

func init() {
	migrations = append(migrations, MemoryV2DDL)
	migrationsPostgres = append(migrationsPostgres, strings.ReplaceAll(MemoryV2DDL, "id INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"))
	identityTables = append(identityTables, "memory_state_events")
	for _, spec := range []struct{ table, columns string }{
		{"memory_session_bindings", "handle project_id session_id assistant native_id checkout parent_handle seen_revisions provenance created_at"},
		{"memory_capture_batches", "id project_id source_handle executor_handle trigger watermark state generation lease_until retries next_retry manifest_ready created_at updated_at"},
		{"memory_details", "memory_id project_id format_version rationale subject_key scope source_handle content_digest completeness"},
		{"memory_evidence", "id project_id memory_id source_type locator digest excerpt status observed_at verified_at"},
		{"memory_relations", "id project_id source_id target_id relation_type scope rationale evidence_id proposer created_at"},
		{"memory_state_events", "id project_id memory_id relation_id event_kind evidence_id expected_revision actor occurred_at operation_id"},
		{"memory_write_receipts", "project_id operation_id batch_id item_key payload_digest state memory_id result_json created_at"},
	} {
		transferColumns = append(transferColumns, struct {
			table string
			cols  []string
		}{spec.table, strings.Fields(spec.columns)})
	}
}

func (s *Store) UpgradeMemoryV2() error {
	if err := migrateTo(s.DB, s.Backend, 16); err != nil {
		return err
	}
	s.MemoryV2 = true
	return nil
}

func isV2Table(table string) bool {
	return strings.HasPrefix(table, "memory_") && table != "memory_usage_events" && table != "memory_team_supersedes"
}
