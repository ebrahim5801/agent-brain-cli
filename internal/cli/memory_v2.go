func newMemoryUpgradeV2Cmd() *cobra.Command {
	var apply bool
	var previewBackend string
	c := &cobra.Command{Use: "upgrade-v2", Short: "Preview the additive local memory schema; apply only after backup and review", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, args []string) error {
		if !apply {
			ddl := store.MemoryV2DDL
			switch previewBackend {
			case "sqlite":
			case "postgres":
				ddl = strings.ReplaceAll(ddl, "id INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
			default:
				return fmt.Errorf("preview backend must be sqlite or postgres")
			}
			if _, err := fmt.Fprint(cmd.OutOrStdout(), ddl); err != nil {
				return err
			}
			fmt.Fprintln(cmd.OutOrStdout(), "Preview only. Back up the configured database and align all binaries before using --apply.")
			return nil
		}
		st, err := store.Open()
		if err != nil {
			return err
		}
		defer st.Close()
		if err := st.UpgradeMemoryV2(); err != nil {
			return err
		}
		fmt.Fprintln(cmd.OutOrStdout(), "Memory V2 additive schema activated. Historical memory rows were not rewritten. Restart all MCP/daemon processes; retain a V2-compatible binary for rollback.")
		return nil
	}}
	c.Flags().StringVar(&previewBackend, "preview-backend", "sqlite", "DDL preview dialect; --apply always uses the configured store backend")
	c.Flags().BoolVar(&apply, "apply", false, "explicitly apply the reviewed additive schema to the configured store")
	return c
}

func newMemoryHistoryCmd() *cobra.Command {
	return &cobra.Command{Use: "history", Short: "Show preserved memory records and lifecycle events for this project", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, args []string) error {
		st, err := store.Open()
		if err != nil {
			return err
		}
		defer st.Close()
		pid, _, found, err := currentProject(st)
		if err != nil {
			return err
		}
		if !found {
			fmt.Fprintln(cmd.OutOrStdout(), "No project history.")
			return nil
		}
		history, err := st.MemorySnapshot(pid, map[string]bool{"*": true})
		if err != nil {
			return err
		}
		for i := range history.Entries {
			m := &history.Entries[i]
			m.Content = redact.Apply(m.Content)
			m.Details.Rationale = redact.Apply(m.Details.Rationale)
		}
		for i := range history.Evidence {
			history.Evidence[i].Excerpt = redact.Apply(history.Evidence[i].Excerpt)
		}
		enc := json.NewEncoder(cmd.OutOrStdout())
		enc.SetIndent("", "  ")
		return enc.Encode(history)
	}}
}

func newMemoryReviewCmd() *cobra.Command {
	return &cobra.Command{Use: "verify <id>...", Short: "Review bounded local evidence references without rewriting history", Args: cobra.RangeArgs(1, 16), RunE: func(cmd *cobra.Command, args []string) error {
		st, err := store.Open()
		if err != nil {
			return err
		}
		defer st.Close()
		pid, _, found, err := currentProject(st)
		if err != nil {
			return err
		}
		if !found {
			return store.ErrMemoryNotFound
		}
		var ids []int64
		for _, arg := range args {
			id, err := parseMemoryID(arg)
			if err != nil {
				return err
			}
			ids = append(ids, id)
		}
		dir, _ := os.Getwd()
		result, err := memory.ReviewSources(st, pid, dir, ids)
		if err != nil {
			return err
		}
		return json.NewEncoder(cmd.OutOrStdout()).Encode(result)
	}}
}
func newMemoryV2StatusCmd() *cobra.Command {
	return &cobra.Command{Use: "status", Short: "Report local memory schema, binding and capture reliability", Args: cobra.NoArgs, RunE: func(cmd *cobra.Command, args []string) error {
		st, err := store.Open()
		if err != nil {
			return err
		}
		defer st.Close()
		version, err := st.SchemaVersion()
		if err != nil {
			return err
		}
		report := map[string]any{"schema": version, "v2_active": st.MemoryV2, "automation_enabled": os.Getenv("AGENT_BRAIN_MEMORY_V2_AUTOMATION") != "off", "ranking_enabled": os.Getenv("AGENT_BRAIN_MEMORY_V2_RANKING") != "off"}
		if path, err := os.Executable(); err == nil {
			report["running_executable"] = path
			if raw, err := os.ReadFile(path); err == nil {
				h := sha256.Sum256(raw)
				report["running_build_sha256"] = hex.EncodeToString(h[:])
			}
		}
		caps := map[string]any{}
		for _, a := range assistant.Registry() {
			state, err := a.State()
			caps[a.Name()] = map[string]any{"detected": state.Detected, "installed_events": state.HookEvents, "expected_events": state.HookEventsWanted, "mcp_registered": state.MCPRegistered, "context_envelope": a.InjectionResponse("probe") != "", "stop_envelope": a.StopResponse("probe") != "", "state_available": err == nil, "notes": state.Notes}
		}
		report["assistants"] = caps
		pid, _, found, err := currentProject(st)
		if err != nil {
			return err
		}
		if found && st.MemoryV2 {
			batches, err := st.PendingCaptures(pid)
			if err != nil {
				return err
			}
			report["pending_captures"] = batches
			var bindings int64
			var last string
			var empty int64
			if err := st.QueryRow(`SELECT COUNT(*) FROM memory_session_bindings WHERE project_id=?`, pid).Scan(&bindings); err != nil {
				return err
			}
			report["bindings"] = bindings
			if err := st.QueryRow(`SELECT COALESCE(MAX(updated_at),''),COUNT(CASE WHEN state='no_durable_changes' THEN 1 END) FROM memory_capture_batches WHERE project_id=? AND state IN ('persisted','no_durable_changes')`, pid).Scan(&last, &empty); err != nil {
				return err
			}
			report["last_acknowledged_capture"] = last
			report["no_change_captures"] = empty
			if len(batches) > 0 {
				var oldest string
				if err := st.QueryRow(`SELECT MIN(created_at) FROM memory_capture_batches WHERE project_id=? AND state NOT IN ('persisted','no_durable_changes')`, pid).Scan(&oldest); err != nil {
					return err
				}
				report["oldest_pending_capture"] = oldest
			}
		}
		enc := json.NewEncoder(cmd.OutOrStdout())
		enc.SetIndent("", "  ")
		return enc.Encode(report)
	}}
}
